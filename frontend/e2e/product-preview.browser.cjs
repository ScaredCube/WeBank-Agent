test('从账户普通区域开始滑动时滚动列表，不误触拖拽', async ({ browser, baseURL }) => {
  const { context, verifyNoApi } = await isolatedContext(browser, { baseURL, viewport: { width: 390, height: 600 }, hasTouch: true, isMobile: true })
  const page = await context.newPage()
  await page.goto('/product-preview')
  await openPanel(page, '资产')
  const source = page.getByRole('button', { name: /^付款账户.*日常账户/ })
  const rect = await source.boundingBox()
  if (!rect) throw new Error('无法读取账户位置')
  const scrollArea = page.getByRole('region', { name: '资产' }).locator('.scroll-thin')
  const cdp = await context.newCDPSession(page)
  const start = { x: rect.x + 30, y: rect.y + 45 }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [start] })
  for (let distance = 20; distance <= 160; distance += 20) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: start.x, y: start.y - distance }] })
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(() => scrollArea.evaluate((element) => element.scrollTop)).toBeGreaterThan(20)
  await expect(page.getByText(/转账 · .* →/)).toHaveCount(0)
  verifyNoApi()
  await context.close()
})

test('模拟触屏拖拽取消不会产生意图，释放到目标才组合', async ({ browser, baseURL }) => {
  const { context, verifyNoApi } = await isolatedContext(browser, { baseURL, viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  const page = await context.newPage()
  await page.goto('/product-preview')
  await openPanel(page, '资产')
  const handle = page.locator('[data-drag-handle]').first()
  const target = page.getByRole('button', { name: /^小林/ })
  const a = await handle.boundingBox()
  const b = await target.boundingBox()
  if (!a || !b) throw new Error('无法读取触控目标位置')
  const start = { x: a.x + a.width / 2, y: a.y + a.height / 2 }
  const end = { x: b.x + b.width / 2, y: b.y + b.height / 2 }
  const cdp = await context.newCDPSession(page)
  async function begin() {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [start] })
    await page.waitForTimeout(300)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [end] })
  }
  await begin()
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
  await expect(page.getByRole('region', { name: '资产' })).toBeVisible()
  await expect(page.getByText('转账 · 日常账户 → 小林')).toHaveCount(0)
  await expect.poll(async () => {
    const box = await handle.boundingBox()
    return box ? Math.hypot(box.x + box.width / 2 - start.x, box.y + box.height / 2 - start.y) : Infinity
  }).toBeLessThan(3)
  await begin()
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(page.getByText('转账 · 日常账户 → 小林')).toBeVisible()
  verifyNoApi()
  await context.close()
})

