const { test, expect } = require('@playwright/test')

async function openPanel(page, name) {
  await page.getByRole('button', { name: '打开导航和会话列表' }).click()
  await page.getByRole('button', { name, exact: true }).click()
}

async function isolatedContext(browser, options) {
  let apiCalls = 0
  const context = await browser.newContext(options)
  await context.route('**/api/**', async (route) => { apiCalls++; await route.abort() })
  return { context, verifyNoApi: () => expect(apiCalls).toBe(0) }
}

