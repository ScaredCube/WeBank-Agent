test('资产可通过长按拖拽或键盘组合', async ({ browser, baseURL }) => {
  const { context, verifyNoApi } = await isolatedContext(browser, { baseURL, viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  await page.goto('/product-preview')
  await openPanel(page, '资产')
  const source = page.getByRole('button', { name: /^付款账户.*日常账户/ })
  const target = page.getByRole('button', { name: /^小林/ })
  const a = await source.boundingBox()
  const b = await target.boundingBox()
  if (!a || !b) throw new Error('无法读取资产位置')
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
  await page.mouse.down()
  await page.waitForTimeout(300)
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect(page.getByText('转账 · 日常账户 → 小林')).toBeVisible()
  await page.getByRole('button', { name: '移除' }).click()
  await openPanel(page, '资产')
  await page.getByRole('button', { name: /^付款账户.*日常账户/ }).focus()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: /^小林/ }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('转账 · 日常账户 → 小林')).toBeVisible()
  verifyNoApi()
  await context.close()
})

